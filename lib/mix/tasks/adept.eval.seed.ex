defmodule Mix.Tasks.Adept.Eval.Seed do
  @shortdoc "Seed multi-hop evaluation test cases with LLM-generated references"

  @moduledoc """
  Seeds multi-hop evaluation test cases for the doctor-who corpus.

  The single-chunk synthetic eval set generated by Arcana's built-in
  `generate_test_cases` samples one source chunk and asks the LLM
  "what question would retrieve this?" — which produces tests Pipeline
  is explicitly optimized for and tells us nothing about
  `Arcana.Loop`'s real value proposition: multi-hop synthesis across
  chunks.

  This task seeds ~10 hand-crafted multi-hop questions with
  LLM-generated reference answers. Each question is designed to
  require synthesis across multiple chunks, and the reference answer
  is generated by the LLM with the retrieved chunks in full view
  (the "trusted oracle" pattern).

  Methodology note: the `relevant_chunk_ids` stored on each test case
  are informative, not definitive. For multi-hop questions, many
  different chunk sets can support a correct answer. The primary
  metric for the Pipeline-vs-Loop comparison is answer correctness
  against the `reference_answer` (LLM-as-judge), not retrieval Hit@k.

  ## Usage

      mix adept.eval.seed               # seed only missing questions
      mix adept.eval.seed --reset        # wipe manual cases first

  ## Options

    * `--reset` - delete all existing manual test cases before seeding
    * `--collection NAME` - collection to search against (default: doctor-who)

  Requires whatever env var the configured LLM provider needs
  (e.g. `ZAI_API_TOKEN` for Z.ai).

  Safe to re-run: questions with an existing manual test case having
  the same question text are skipped.
  """

  use Mix.Task

  import Ecto.Query

  alias Arcana.Evaluation
  alias Arcana.Evaluation.TestCase
  alias Adept.Repo

  @requirements ["app.start"]

  # Hand-crafted multi-hop questions about the doctor-who corpus.
  # Each requires synthesis across multiple chunks.
  @questions [
    "Which Time Lords have betrayed the Doctor across the show's history?",
    "What are the main abilities and unusual properties of the TARDIS?",
    "Who are the most notable companions of the Fourth Doctor and what distinguishes each?",
    "How has the Master's character and appearance evolved across different incarnations?",
    "What role did the Daleks play during the Last Great Time War?",
    "What are the known weaknesses of the Cybermen across different eras?",
    "How has Gallifrey's depiction changed between the classic and modern series?",
    "Which historical figures has the Doctor met, and in which stories?",
    "What is the evolution of the sonic screwdriver's capabilities over the show's run?",
    "Which companions have become Time Lords or Time Lord-like beings?"
  ]

  @impl Mix.Task
  def run(args) do
    {opts, _, _} =
      OptionParser.parse(args,
        strict: [reset: :boolean, collection: :string]
      )

    collection = Keyword.get(opts, :collection, "doctor-who")
    reset? = Keyword.get(opts, :reset, false)
    llm = Application.fetch_env!(:arcana, :llm)

    if reset? do
      Mix.shell().info(IO.ANSI.format([:yellow, "Resetting existing manual test cases..."]))
      Repo.delete_all(from(tc in TestCase, where: tc.source == :manual))
    end

    existing =
      Repo.all(from(tc in TestCase, where: tc.source == :manual, select: tc.question))
      |> MapSet.new()

    results = Enum.map(@questions, &seed_one(&1, existing, collection, llm))

    seeded = Enum.count(results, &(&1 == :seeded))
    skipped = Enum.count(results, &(&1 == :skipped))

    Mix.shell().info(
      IO.ANSI.format([:bright, "\n=== Done: #{seeded} seeded, #{skipped} skipped ==="])
    )
  end

  defp seed_one(question, existing, collection, llm) do
    if MapSet.member?(existing, question) do
      Mix.shell().info(IO.ANSI.format([:faint, "[skip] ", question]))
      :skipped
    else
      Mix.shell().info(IO.ANSI.format([:cyan, "[seed] ", question]))

      # Pull the top retrieved chunks via the production baseline
      # (Arcana.search/2 with default config: vector + graph + rerank).
      # These become the relevant_chunk_ids on the test case.
      case Arcana.search(question, repo: Repo, collection: collection, limit: 10) do
        {:ok, []} ->
          Mix.shell().info(IO.ANSI.format([:red, "  no chunks returned, skipping"]))
          :skipped

        {:ok, chunks} ->
          insert_case(question, chunks, llm)
          :seeded

        {:error, reason} ->
          Mix.shell().info(IO.ANSI.format([:red, "  search failed: #{inspect(reason)}"]))
          :skipped
      end
    end
  end

  defp insert_case(question, chunks, llm) do
    chunks_text =
      chunks
      |> Enum.with_index(1)
      |> Enum.map_join("\n\n", fn {c, i} -> "#{i}. #{c.text}" end)

    prompt = reference_prompt(question, chunks_text)

    reference_answer =
      case Arcana.LLM.complete(llm, prompt, [], []) do
        {:ok, text} -> String.trim(text)
        {:error, reason} -> Mix.raise("LLM failed for #{inspect(question)}: #{inspect(reason)}")
      end

    {:ok, _tc} =
      Evaluation.create_test_case(
        repo: Repo,
        question: question,
        relevant_chunk_ids: Enum.map(chunks, & &1.id),
        reference_answer: reference_answer
      )

    Mix.shell().info(
      IO.ANSI.format([
        :faint,
        "  reference: ",
        String.slice(reference_answer, 0, 100),
        "..."
      ])
    )
  end

  defp reference_prompt(question, chunks_text) do
    """
    You are writing a ground-truth reference answer for a retrieval
    evaluation. You have been given a set of relevant chunks from a
    Doctor Who knowledge base. Your job is to write a correct, complete,
    well-structured answer to the question using only the information
    in the chunks.

    Rules:
    - Use only facts present in the chunks. Do not add outside knowledge.
    - Cover every major fact relevant to the question.
    - Write in flowing prose, not bullet points, unless the question
      obviously calls for a list.
    - Do not reference the chunks explicitly (no "according to the text").
    - Keep the answer to 150-300 words.

    Question: #{question}

    Relevant chunks:
    #{chunks_text}

    Reference answer:
    """
  end
end
